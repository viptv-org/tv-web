#!/usr/bin/env python3
"""Rebuild committed TV textures and their browser cache versions (Pillow)."""
from pathlib import Path
import hashlib
import json
import runpy
import re

ROOT = Path(__file__).resolve().parents[1]
scripts = ("build-welcome-wall.py", "build-tv-masks.py")
inputs = [ROOT / "scripts" / name for name in (*scripts, "build-tv-artwork.py")]
for script in scripts:
    result = runpy.run_path(str(ROOT / "scripts" / script), run_name="__main__")
    if script == "build-welcome-wall.py":
        inputs.extend([result["source"], *result["art"].values()])
inputs.extend(ROOT / "roku/pkg/assets" / name for name in ("welcome-scrim.png", "welcome-vignette.png"))
lines = ['/** Generated by scripts/build-tv-artwork.py. */']
browser_outputs = []
for function, filename in (("welcomeWallSource", "welcome-wall.webp"), ("backdropScrimSource", "hero-scrim.png"), ("topbarScrimSource", "topbar-scrim.png"), ("busySpinnerSource", "busy-spinner.png")):
    source = ROOT / "public/tv-artwork" / filename
    version = hashlib.sha256(source.read_bytes()).hexdigest()[:20]
    target = source.with_name(version + source.suffix)
    source.replace(target)
    browser_outputs.append(target)
    lines.append(f'''export function {function}() {{
  return typeof (globalThis as any).__SolidTVRokuRenderer !== "undefined"
    ? "pkg:/assets/{filename}"
    : `${{import.meta.env.BASE_URL}}tv-artwork/{target.name}`;
}}''')
(ROOT / "src/tv-solid/remote/tv-artwork.generated.ts").write_text("\n".join(lines) + "\n")
outputs = [ROOT / "src/tv-solid/remote/tv-artwork.generated.ts"]
outputs.extend(browser_outputs)
outputs.extend(ROOT / folder / name for folder in ("roku/pkg/assets",)
               for name in ("welcome-wall.webp", "hero-scrim.png", "topbar-scrim.png", "busy-spinner.png"))
for path in (ROOT / "public/tv-artwork").iterdir():
    if re.fullmatch(r"[a-f0-9]{20}\.(?:png|webp)", path.name) and path not in browser_outputs:
        path.unlink()
def hashes(paths):
    return {str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest() for path in paths}
(ROOT / "src/tv-solid/remote/tv-artwork.manifest.json").write_text(
    json.dumps({"version": 1, "inputs": hashes(inputs), "outputs": hashes(outputs)}, indent=2) + "\n")
